"""make_pad_atlas -- the key pads' labels and icons for LEGACY (host/pad_atlas.h).

LEGACY draws the old apps' key pads itself (host/pad.cpp), in C++ without Slint, so their labels and icons are
alpha masks made here: NeoSans (Inter + Noto Armenian, OFL) text and neoui's own icons (ui/icons/sys, Apache-2.0),
rasterized at 3 px per dp (the Pixel's 1080-wide screen) and cropped to their ink. pad.cpp tints them and scales
them to the screen's dp. Run it again after changing a label, size or icon:

    uv run --no-project --with pillow --with resvg-py python tools/make_pad_atlas.py ../neoui
"""

import io
import os
import sys

from PIL import Image, ImageDraw, ImageFont

SCALE = 3  # px per dp of the masks

# (id, kind, what, size dp, weight): text in NeoSans, or an icon from neoui/ui/icons/sys
GLYPHS = [
    ("Nav", "text", "Nav", 14, "SemiBold"),
    ("Game", "text", "Game", 14, "SemiBold"),
    ("Num", "text", "123", 14, "SemiBold"),
    ("Abc", "text", "Abc", 14, "SemiBold"),
    ("Hide", "text", "Hide", 14, "SemiBold"),
    ("Portrait", "text", "Portrait", 14, "SemiBold"),
    ("Ok", "text", "OK", 17, "SemiBold"),
    ("C", "text", "C", 19, "SemiBold"),
    ("A", "text", "A", 22, "SemiBold"),
    ("B", "text", "B", 22, "SemiBold"),
    *[(f"D{d}", "text", str(d), 19, "Regular") for d in range(10)],
    ("Star", "text", "*", 19, "Regular"),
    ("Hash", "text", "#", 19, "Regular"),
    *[
        (f"L{d}", "text", letters, 9, "Regular")
        for d, letters in [
            (0, "+"),
            (2, "ABC"),
            (3, "DEF"),
            (4, "GHI"),
            (5, "JKL"),
            (6, "MNO"),
            (7, "PQRS"),
            (8, "TUV"),
            (9, "WXYZ"),
        ]
    ],
    ("Call", "icon", "call", 20, None),
    ("End", "icon", "end_call", 20, None),
    ("Edit", "icon", "edit", 20, None),
    ("Rotate", "icon", "refresh", 18, None),
    ("Keyboard", "icon", "keyboard", 22, None),
]


def text_mask(fonts, text, size_dp, weight):
    font = ImageFont.truetype(
        os.path.join(fonts, f"NeoSans-{weight}.ttf"), size_dp * SCALE
    )
    left, top, right, bottom = font.getbbox(text)
    im = Image.new("L", (int(right - left) + 4, int(bottom - top) + 4), 0)
    ImageDraw.Draw(im).text((2 - left, 2 - top), text, font=font, fill=255)
    return im


def icon_mask(icons, name, size_dp):
    import resvg_py

    px = size_dp * SCALE
    with open(os.path.join(icons, f"{name}.svg")) as f:
        png = resvg_py.svg_to_bytes(svg_string=f.read(), width=px, height=px)
    return Image.open(io.BytesIO(bytes(png))).getchannel("A")


def crop(im):
    box = im.getbbox()
    assert box, "an empty glyph"
    return im.crop(box)


def main():
    neoui = (
        sys.argv[1]
        if len(sys.argv) > 1
        else os.path.join(os.path.dirname(__file__), "..", "..", "neoui")
    )
    fonts = os.path.join(neoui, "ui", "fonts")
    icons = os.path.join(neoui, "ui", "icons", "sys")
    out = os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "host", "pad_atlas.h"
    )

    data = bytearray()
    entries = []
    for gid, kind, what, size, weight in GLYPHS:
        im = crop(
            text_mask(fonts, what, size, weight)
            if kind == "text"
            else icon_mask(icons, what, size)
        )
        entries.append((gid, im.width, im.height, len(data)))
        data += im.tobytes()

    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by tools/make_pad_atlas.py -- do not edit. The key pads' labels and icons as alpha masks at 3 px",
        "// per dp: NeoSans (Inter + Noto Sans Armenian, OFL-1.1, neoui/ui/fonts) and neoui's icons (Apache-2.0).",
        "#ifndef PAD_ATLAS_H",
        "#define PAD_ATLAS_H",
        "",
        f"const TInt KPadAtlasScale = {SCALE};\t// px per dp",
        "enum TPadGlyph",
        "\t{",
        *[f"\tEGlyph{gid}," for gid, *_ in entries],
        "\tEGlyphCount",
        "\t};",
        "struct TPadGlyphInfo { TUint16 iW, iH; TUint32 iOffset; };",
        "const TPadGlyphInfo KPadGlyphs[EGlyphCount] =",
        "\t{",
        *[f"\t{{ {w}, {h}, {off} }},\t// {gid}" for gid, w, h, off in entries],
        "\t};",
        f"const TUint8 KPadAlpha[{len(data)}] =",
        "\t{",
    ]
    for i in range(0, len(data), 32):
        lines.append("\t" + ",".join(str(b) for b in data[i : i + 32]) + ",")
    lines += ["\t};", "", "#endif", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"{out}: {len(entries)} glyphs, {len(data)} bytes")


if __name__ == "__main__":
    main()
